@pytest.mark.asyncio
async def test_both_providers_timeout_marks_job_failed():
    """When both Gemini and Groq time out, the job status becomes 'failed' with a clear reason."""
    job_id = "test_both_timeout_job"
    req = api.LessonRequest(course="C", topic="T", celebrity="modi")

    # Seed job_status as processing (as happens when background task starts)
    api.job_status[job_id] = {"status": "processing"}
    api.generation_cache["some_key"] = job_id

    gemini_timeout = TimeoutError("Gemini connection timed out after 60s")
    groq_timeout = APITimeoutError(request=httpx.Request("POST", "https://api.groq.com"))

    with patch.object(api.gemini_client.models, "generate_content", side_effect=gemini_timeout), \
         patch.object(api.groq_client.chat.completions, "create", side_effect=groq_timeout):

        await api.process_lesson(req, job_id)

    # Status must be 'failed', never left as 'processing'
    assert api.job_status[job_id]["status"] == "failed"
    assert api.job_status[job_id]["status"] != "processing"

    # Must provide clear reason explaining both failures
    error_msg = api.job_status[job_id].get("error", "")
    assert "Gemini" in error_msg
    assert "Groq" in error_msg
    assert "failed" in error_msg.lower() or "timeout" in error_msg.lower()

    # Reason field should also be populated
    assert "reason" in api.job_status[job_id]
    assert api.job_status[job_id]["reason"] == error_msg

    # Timestamps recorded
    assert "failed_at" in api.job_status[job_id]["meta"]["timestamps"]

    # Cache entry removed
    assert "some_key" not in api.generation_cache


