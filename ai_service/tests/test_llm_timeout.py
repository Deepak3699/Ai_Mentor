class SlowHTTPHandler(http.server.BaseHTTPRequestHandler):
    """HTTP handler that delays responding to simulate a hanging/slow upstream provider."""
    def do_POST(self):
        time.sleep(1.0)
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.end_headers()
        self.wfile.write(b"{}")

    def log_message(self, *args):
        pass  # Suppress server logging during tests


@pytest.fixture(scope="module")
def slow_upstream_server():
    server = http.server.HTTPServer(("127.0.0.1", 0), SlowHTTPHandler)
    port = server.server_port
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    yield f"http://127.0.0.1:{port}"
    server.shutdown()


def test_slow_gemini_provider_aborts_with_timeout(slow_upstream_server):
    """Mocks a slow upstream provider and asserts that the Gemini client call aborts."""
    from google import genai
    from google.genai import types

    # Configure client pointing to slow upstream server with a 150ms timeout
    test_client = genai.Client(api_key="test-key")
    start = time.time()

    with pytest.raises(httpx.TimeoutException):
        test_client.models.generate_content(
            model="gemini-2.5-flash",
            contents="hello",
            config=types.GenerateContentConfig(
                http_options=types.HttpOptions(
                    base_url=slow_upstream_server,
                    timeout=150,  # 150ms timeout
                )
            ),
        )

    elapsed = time.time() - start
    # The call should have aborted within ~0.6s, well below the 1.0s slow response
    assert elapsed < 0.9, f"Call took {elapsed}s, expected it to abort earlier"


def test_slow_groq_provider_aborts_with_timeout(slow_upstream_server):
    """Mocks a slow upstream provider and asserts that the Groq client call aborts."""
    from groq import Groq

    # Configure Groq client pointing to slow server with a 0.15s timeout
    test_client = Groq(
        base_url=slow_upstream_server,
        api_key="test-key",
        timeout=0.15,
        max_retries=0,
    )
    start = time.time()

    with pytest.raises(APITimeoutError):
        test_client.chat.completions.create(
            model="llama-3.3-70b-versatile",
            messages=[{"role": "user", "content": "hi"}],
        )

    elapsed = time.time() - start
    assert elapsed < 0.9, f"Call took {elapsed}s, expected it to abort earlier"
